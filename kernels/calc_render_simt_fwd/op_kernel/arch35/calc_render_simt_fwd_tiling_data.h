// ROLE: CalcRenderSimtFwdTilingData —— host/device 全局唯一定义。
//   - device：op_kernel/arch35/calc_render_simt_fwd.h 经本文件取用（kernel 入口
//     REGISTER_TILING_DEFAULT + GET_TILING_DATA_WITH_STRUCT 消费）。
//   - host：op_host/arch35/calc_render_simt_fwd_tiling.h 经相对路径转发本文件，
//     op_host/arch35/calc_render_simt_fwd_tiling.cpp 以 GetRawTilingData 裸填 6 字段
//     并 SetDataSize(sizeof)。
//
// 定义置于 kernel 侧的原因：二进制编译（kernels/CMakeLists.txt add_bin_compile_target）
// 会把 op_kernel 源码平铺复制到 build/.../binary/<soc>/src/，跨目录相对包含
// （../../op_host/arch35/...）在该平铺目录下无法解析而编译失败；本工程既有约定
// （flash_gaussian_build_mask_*_tiling_struct.h、calc_render_simt_bwd_tiling_struct.h）
// 同样是 host 经相对路径包含 kernel 侧 tiling 结构体定义。
//
// 字段/偏移与设计 TilingData.md 逐字段一致，不增不删；单分支 tilingKey=0。
#ifndef CALC_RENDER_SIMT_FWD_TILING_DATA_H
#define CALC_RENDER_SIMT_FWD_TILING_DATA_H

#include <stdint.h>
#include <stddef.h>

// DCache 预留（字节）：host SetLocalMemorySize(ubSize − DCACHE_RESERVED) 与 kernel
// 侧单 buffer 布局容量校验同源共享（Ascend950：248KB − 128KB = 120KB 可用 UB）。
constexpr uint64_t DCACHE_RESERVED = 128ULL * 1024;

struct alignas(8) CalcRenderSimtFwdTilingData {
    int64_t  nPixel;    // tile 像素数，设计契约固定 1024（32×32 tile，T1/T9；host 断言/兜底）
    int64_t  tileNum;   // tile 总数 = tileCoords.dim(0)，运行时可变维
    int64_t  nGauss;    // 高斯总数 = gs.dim(0)，运行时可变维（< 2^31，T8 前提）
    int64_t  totalGauss; // gsIds 长度 = gsIds.dim(0)（TotalGauss，Task 30：kernel 段界
                         // 防御裁剪上界 nIds，对齐 golden.py:74-76 clip(segStart/segEnd,0,nIds)）
    uint64_t ubSize;    // GetCoreMemSize(UB) 动态查询的 UB 总容量（字节）
    uint32_t blockDim;  // AIV 核数 = GetCoreNumAiv()（为 0 时单核兜底 1）；与 SetBlockDim 同源同值
};

// ABI 契约：8+8+8+8+8+8+4(+4 padding) = 52 字节有效、48B 对齐槽（Task 30 新增
// totalGauss 后 40B→48B 序列化布局），字段偏移与设计字段表一致。
static_assert(offsetof(CalcRenderSimtFwdTilingData, nPixel) == 0, "nPixel ABI");
static_assert(offsetof(CalcRenderSimtFwdTilingData, tileNum) == 8, "tileNum ABI");
static_assert(offsetof(CalcRenderSimtFwdTilingData, nGauss) == 16, "nGauss ABI");
static_assert(offsetof(CalcRenderSimtFwdTilingData, totalGauss) == 24, "totalGauss ABI");
static_assert(offsetof(CalcRenderSimtFwdTilingData, ubSize) == 32, "ubSize ABI");
static_assert(offsetof(CalcRenderSimtFwdTilingData, blockDim) == 40, "blockDim ABI");
static_assert(alignof(CalcRenderSimtFwdTilingData) == 8, "tiling alignment ABI");
static_assert(sizeof(CalcRenderSimtFwdTilingData) == 48, "tiling ABI");

#endif // CALC_RENDER_SIMT_FWD_TILING_DATA_H

