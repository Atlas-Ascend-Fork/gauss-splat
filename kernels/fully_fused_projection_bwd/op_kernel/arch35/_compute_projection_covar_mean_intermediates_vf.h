        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(r12, view_ub + 6);
        MicroAPI::RegTensor<float> ty;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(ty, view_ub + 7);
        MicroAPI::RegTensor<float> r20;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(r20, view_ub + 8);
        MicroAPI::RegTensor<float> r21;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(r21, view_ub + 9);
        MicroAPI::RegTensor<float> r22;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(r22, view_ub + 10);
        MicroAPI::RegTensor<float> tz;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(tz, view_ub + 11);
        MicroAPI::RegTensor<float> fx;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(fx, k_ub);
        MicroAPI::RegTensor<float> fy;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(fy, k_ub + 4);
        MicroAPI::RegTensor<float> mx;
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(mx, means_ub, 1, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> my;
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(my, means_ub + 1 * 1024, 1, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> mz;
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(mz, means_ub + 2 * 1024, 1, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> pcx;
        MicroAPI::Mul(_tmp_reg_1, r00, mx, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, r01, my, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, _tmp_reg_1, _tmp_reg_2, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, r02, mz, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, _tmp_reg_1, _tmp_reg_2, _tmp_maskreg_0);
        MicroAPI::Add(pcx, _tmp_reg_1, tx, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> pcy;
        MicroAPI::Mul(_tmp_reg_1, r10, mx, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, r11, my, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, _tmp_reg_1, _tmp_reg_2, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, r12, mz, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, _tmp_reg_1, _tmp_reg_2, _tmp_maskreg_0);
        MicroAPI::Add(pcy, _tmp_reg_1, ty, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> pcz;
        MicroAPI::Mul(_tmp_reg_1, r20, mx, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, r21, my, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, _tmp_reg_1, _tmp_reg_2, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, r22, mz, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, _tmp_reg_1, _tmp_reg_2, _tmp_maskreg_0);
        MicroAPI::Add(pcz, _tmp_reg_1, tz, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> one;
        MicroAPI::Duplicate(one, 1.0f, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> zero;
        MicroAPI::Duplicate(zero, 0.0f, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> half;
        MicroAPI::Duplicate(half, 0.5f, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> clip_margin;
        MicroAPI::Duplicate(clip_margin, 0.3f, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> neg_one;
        MicroAPI::Duplicate(neg_one, -1.0f, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> inv_z;
        MicroAPI::Div(inv_z, one, pcz, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> inv_z2;
        MicroAPI::Mul(inv_z2, inv_z, inv_z, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> width_f;
        MicroAPI::Duplicate(width_f, width, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> height_f;
        MicroAPI::Duplicate(height_f, height, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> cx;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(cx, k_ub + 2);
        MicroAPI::RegTensor<float> cy;
        MicroAPI::DataCopy<float, MicroAPI::LoadDist::DIST_BRC_B32>(cy, k_ub + 5);
        MicroAPI::RegTensor<float> half_width;
        MicroAPI::Mul(half_width, half, width_f, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> half_height;
        MicroAPI::Mul(half_height, half, height_f, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> lim_x_pos;
        MicroAPI::Sub(_tmp_reg_1, width_f, cx, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, clip_margin, half_width, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, _tmp_reg_1, _tmp_reg_2, _tmp_maskreg_0);
        MicroAPI::Div(lim_x_pos, _tmp_reg_1, fx, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> lim_x_neg;
        MicroAPI::Mul(_tmp_reg_1, clip_margin, half_width, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, cx, _tmp_reg_1, _tmp_maskreg_0);
        MicroAPI::Div(lim_x_neg, _tmp_reg_1, fx, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> lim_y_pos;
        MicroAPI::Sub(_tmp_reg_1, height_f, cy, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, clip_margin, half_height, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, _tmp_reg_1, _tmp_reg_2, _tmp_maskreg_0);
        MicroAPI::Div(lim_y_pos, _tmp_reg_1, fy, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> lim_y_neg;
        MicroAPI::Mul(_tmp_reg_1, clip_margin, half_height, _tmp_maskreg_0);
        MicroAPI::Add(_tmp_reg_1, cy, _tmp_reg_1, _tmp_maskreg_0);
        MicroAPI::Div(lim_y_neg, _tmp_reg_1, fy, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> norm_x;
        MicroAPI::Mul(norm_x, pcx, inv_z, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> norm_y;
        MicroAPI::Mul(norm_y, pcy, inv_z, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> raw_j02;
        MicroAPI::Mul(_tmp_reg_1, neg_one, fx, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_1, _tmp_reg_1, pcx, _tmp_maskreg_0);
        MicroAPI::Mul(raw_j02, _tmp_reg_1, inv_z2, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> raw_j12;
        MicroAPI::Mul(_tmp_reg_1, neg_one, fy, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_1, _tmp_reg_1, pcy, _tmp_maskreg_0);
        MicroAPI::Mul(raw_j12, _tmp_reg_1, inv_z2, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> lower;
        MicroAPI::Mul(lower, neg_one, lim_x_neg, _tmp_maskreg_0);
        MicroAPI::MaskReg x_inside_low = MicroAPI::CreateMask<float, MicroAPI::MaskPattern::ALL>();
        MicroAPI::Compare<float, CMPMODE::GE>(x_inside_low, norm_x, lower, _tmp_maskreg_0);
        MicroAPI::MaskReg x_inside_high = MicroAPI::CreateMask<float, MicroAPI::MaskPattern::ALL>();
        MicroAPI::Compare<float, CMPMODE::LE>(x_inside_high, norm_x, lim_x_pos, _tmp_maskreg_0);
        MicroAPI::MaskReg x_inside = MicroAPI::CreateMask<float, MicroAPI::MaskPattern::ALL>();
        MicroAPI::MaskAnd(x_inside, x_inside_low, x_inside_high, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> pcx_clamped_norm;
        MicroAPI::Copy(pcx_clamped_norm, norm_x, _tmp_maskreg_0);
        MicroAPI::Min(pcx_clamped_norm, pcx_clamped_norm, lim_x_pos, _tmp_maskreg_0);
        MicroAPI::Max(pcx_clamped_norm, pcx_clamped_norm, lower, _tmp_maskreg_0);
        MicroAPI::Mul(pcx, pcz, pcx_clamped_norm, _tmp_maskreg_0);
        MicroAPI::Mul(lower, neg_one, lim_y_neg, _tmp_maskreg_0);
        MicroAPI::MaskReg y_inside_low = MicroAPI::CreateMask<float, MicroAPI::MaskPattern::ALL>();
        MicroAPI::Compare<float, CMPMODE::GE>(y_inside_low, norm_y, lower, _tmp_maskreg_0);
        MicroAPI::MaskReg y_inside_high = MicroAPI::CreateMask<float, MicroAPI::MaskPattern::ALL>();
        MicroAPI::Compare<float, CMPMODE::LE>(y_inside_high, norm_y, lim_y_pos, _tmp_maskreg_0);
        MicroAPI::MaskReg y_inside = MicroAPI::CreateMask<float, MicroAPI::MaskPattern::ALL>();
        MicroAPI::MaskAnd(y_inside, y_inside_low, y_inside_high, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> pcy_clamped_norm;
        MicroAPI::Copy(pcy_clamped_norm, norm_y, _tmp_maskreg_0);
        MicroAPI::Min(pcy_clamped_norm, pcy_clamped_norm, lim_y_pos, _tmp_maskreg_0);
        MicroAPI::Max(pcy_clamped_norm, pcy_clamped_norm, lower, _tmp_maskreg_0);
        MicroAPI::Mul(pcy, pcz, pcy_clamped_norm, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> j00;
        MicroAPI::Mul(j00, fx, inv_z, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> j11;
        MicroAPI::Mul(j11, fy, inv_z, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> j02;
        MicroAPI::Mul(_tmp_reg_1, neg_one, fx, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_1, _tmp_reg_1, pcx, _tmp_maskreg_0);
        MicroAPI::Mul(j02, _tmp_reg_1, inv_z2, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> j12;
        MicroAPI::Mul(_tmp_reg_1, neg_one, fy, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_1, _tmp_reg_1, pcy, _tmp_maskreg_0);
        MicroAPI::Mul(j12, _tmp_reg_1, inv_z2, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> xmask;
        MicroAPI::Select(xmask, one, zero, x_inside);
        MicroAPI::RegTensor<float> ymask;
        MicroAPI::Select(ymask, one, zero, y_inside);
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(proj_covar_ub + 3 * 64, j00, 1, _tmp_maskreg_0);
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(proj_covar_ub + 4 * 64, j11, 1, _tmp_maskreg_0);
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(proj_covar_ub + 5 * 64, j02, 1, _tmp_maskreg_0);
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(proj_covar_ub + 6 * 64, j12, 1, _tmp_maskreg_0);
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(proj_covar_ub + 7 * 64, pcx, 1, _tmp_maskreg_0);
