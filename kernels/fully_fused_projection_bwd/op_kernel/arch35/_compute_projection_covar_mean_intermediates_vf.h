        MicroAPI::RegTensor<float> t01;
        MicroAPI::Mul(_tmp_reg_1, a, vb, _tmp_maskreg_0);
        MicroAPI::Mul(_tmp_reg_2, b, vd, _tmp_maskreg_0);
