        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(opacity_in, opacities_in_ub, 1, _tmp_maskreg_0);
        MicroAPI::RegTensor<float> compensation;
        MicroAPI::DataCopy<float, MicroAPI::DataCopyMode::DATA_BLOCK_COPY>(compensation, compensation_ub, 1, _tmp_maskreg_0);
